#!/usr/bin/env python3
"""Writes src/indexing/fts5TokenChars.ts: the code points SQLite's FTS5 `unicode61` tokenizer
reads as token characters by default, as ranges.

The default is categories L*, N* and Co, judged by SQLite's own Unicode tables
(fts5_unicode2.c), plus every code point those tables don't know: sqlite3Fts5UnicodeCatParse
always admits category 0. So emoji newer than the tables are words to it, and older ones
aren't. AtlasKit's index uses the system SQLite, so the web follows SQLite's tables too. Run with
the path to an SQLite amalgamation:

    scripts/gen-fts5-token-chars.py path/to/sqlite3.c
"""
import os, re, sys

src = open(sys.argv[1]).read()
version = re.search(r'#define SQLITE_VERSION\s+"([^"]+)"', src).group(1)

def table(name):
    body = src[src.index(f'static u16 {name}[] = {{'):]
    body = body[body.index('{') + 1:body.index('};')]
    return [int(n) for n in re.findall(r'\d+', body)]

block, keys, data = table('aFts5UnicodeBlock'), table('aFts5UnicodeMap'), table('aFts5UnicodeData')

def category(c):
    # sqlite3Fts5UnicodeCategory
    if c >= 1 << 20:
        return 0
    lo, hi, key, res = block[c >> 16], block[1 + (c >> 16)], c & 0xFFFF, -1
    while hi > lo:
        mid = (hi + lo) // 2
        if key >= keys[mid]:
            res, lo = mid, mid + 1
        else:
            hi = mid
    if res < 0 or key >= keys[res] + (data[res] >> 5):
        return 0
    ret = data[res] & 0x1F
    return ret if ret != 30 else (5 if (key - keys[res]) & 1 else 9)

# "L* N* Co", as sqlite3Fts5UnicodeCatParse numbers them, and 0, which it always sets.
token = {0, 5, 6, 7, 8, 9, 30, 13, 14, 15, 31}
ranges, start = [], None
for c in range(0x80, 0x110000):
    if category(c) in token:
        if start is None:
            start = c
    elif start is not None:
        ranges += [start, c - 1]
        start = None
if start is not None:
    ranges += [start, 0x10FFFF]

lines = []
for i in range(0, len(ranges), 16):
    lines.append('  ' + ', '.join(f'0x{n:x}' for n in ranges[i:i + 16]) + ',')
out = os.path.join(os.path.dirname(__file__), '..', 'src', 'indexing', 'fts5TokenChars.ts')
with open(out, 'w') as f:
    f.write(f"""// Generated by scripts/gen-fts5-token-chars.py from SQLite {version}. Do not edit.
//
// The non-ASCII code points FTS5's unicode61 tokenizer reads as token characters by default:
// categories L*, N* and Co in SQLite's own Unicode tables, and whatever those tables don't
// know (category 0). As inclusive [first, last] pairs.
// prettier-ignore
export const TOKEN_CHAR_RANGES = [
{chr(10).join(lines)}
];
""")
print(f'{len(ranges) // 2} ranges from SQLite {version}')
